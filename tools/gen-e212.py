#!/usr/bin/env python3
"""Generate src/e212_generated.rs from an mcc-mnc.org networks.csv.

The air interface only carries MCC/MNC numbers; this turns them into operator
and country names. cellcap keeps a small hand-curated override table in
src/e212.rs (for names like "Telenor (test)"); this generated table is the
broad fallback for every other network.

Data: https://mcc-mnc.org/downloads  (public MCC/MNC list; credit mcc-mnc.org).
Refresh with `make e212-data`, which downloads the CSV and reruns this.

Usage: gen-e212.py <networks.csv> <out.rs>
"""
import csv
import sys


def rust_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> int:
    if len(sys.argv) != 3:
        sys.stderr.write(__doc__)
        return 2
    src, out = sys.argv[1], sys.argv[2]

    operators: dict[tuple[str, str], str] = {}
    countries: dict[str, str] = {}
    with open(src, encoding="utf-8-sig", newline="") as f:
        for row in csv.DictReader(f):
            mcc = (row.get("mcc") or "").strip()
            mnc = (row.get("mnc") or "").strip()
            if not (mcc.isdigit() and mnc != ""):
                continue
            country = (row.get("country") or "").strip()
            # Prefer the consumer brand (e.g. "3"); fall back to the legal name.
            name = (row.get("brand") or "").strip() or (row.get("operator") or "").strip()
            name = " ".join(name.split())  # collapse stray whitespace/newlines
            if country and mcc not in countries:
                countries[mcc] = country
            if name and (mcc, mnc) not in operators:
                operators[(mcc, mnc)] = name

    ops = sorted(operators.items(), key=lambda kv: (int(kv[0][0]), kv[0][1]))
    cos = sorted(countries.items(), key=lambda kv: int(kv[0]))

    with open(out, "w", encoding="utf-8") as w:
        w.write(
            "//! Generated by tools/gen-e212.py from an mcc-mnc.org networks.csv.\n"
            "//! Do not edit by hand; rerun `make e212-data` to refresh.\n"
            "//!\n"
            "//! MCC/MNC operator and country names, data from https://mcc-mnc.org/downloads\n"
            "//! (public MCC/MNC list; credit mcc-mnc.org). This is the broad fallback;\n"
            "//! hand-curated names in e212.rs take precedence.\n"
            "#![allow(clippy::all)]\n\n"
        )
        w.write(f"/// (MCC, MNC) -> operator/brand name. {len(ops)} networks.\n")
        w.write("pub const GEN_OPERATORS: &[(&str, &str, &str)] = &[\n")
        for (mcc, mnc), name in ops:
            w.write(f"    ({rust_str(mcc)}, {rust_str(mnc)}, {rust_str(name)}),\n")
        w.write("];\n\n")
        w.write(f"/// MCC -> country. {len(cos)} countries.\n")
        w.write("pub const GEN_COUNTRIES: &[(&str, &str)] = &[\n")
        for mcc, country in cos:
            w.write(f"    ({rust_str(mcc)}, {rust_str(country)}),\n")
        w.write("];\n")

    sys.stderr.write(f"wrote {out}: {len(ops)} operators, {len(cos)} countries\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
